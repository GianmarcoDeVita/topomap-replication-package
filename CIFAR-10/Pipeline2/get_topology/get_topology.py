def get_test_data():
    # Load CIFAR-10 data
    (x_train, y_train), (x_test, y_test) = cifar10.load_data()
    del x_train, y_train
    # Parse numbers as floats
    x_test = x_test.astype('float32')
    # Normalize data
    x_test = x_test / 255

    return x_test, y_test


