def angle_loss_fn(y_true, y_pred):
    x_p = math.sin(y_pred[:, 0]) * math.cos(y_pred[:, 1])
    y_p = math.sin(y_pred[:, 0]) * math.sin(y_pred[:, 1])
    z_p = math.cos(y_pred[:, 0])

    x_t = math.sin(y_true[:, 0]) * math.cos(y_true[:, 1])
    y_t = math.sin(y_true[:, 0]) * math.sin(y_true[:, 1])
    z_t = math.cos(y_true[:, 0])

    norm_p = math.sqrt(x_p * x_p + y_p * y_p + z_p * z_p)
    norm_t = math.sqrt(x_t * x_t + y_t * y_t + z_t * z_t)

    dot_pt = x_p * x_t + y_p * y_t + z_p * z_t

    angle_value = dot_pt/(norm_p * norm_t)
    angle_value = tf.clip_by_value(angle_value, -0.99999, 0.99999)

    loss_val = (math.acos(angle_value))

    return tf.reduce_mean(loss_val, axis=-1)


def nn(x_img_train, x_ha_train, y_train_labels, x_img_test, x_ha_test, y_test_labels, num_classes, embedding, clustering, experiment, verbose=0):

    if not os.path.exists(os.path.join('trained_models', 'lenet_trained' + "_" + str(embedding) + "_" + str(clustering) + "_" + str(experiment) + '.h5')):

        image_input = Input((36, 60, 1))
        head_pose_input = Input((2,))

        initialiser_normal = RandomNormal(mean=0., stddev=0.1)
        initialiser_const = Constant(value=0)
        initialiser_xavier = GlorotNormal(seed=None)

        x = Conv2D(filters=20,
                     kernel_size=(5, 5),
                     strides=1,
                     padding='valid',
                     kernel_initializer=initialiser_normal,
                     bias_initializer=initialiser_const,
                     activation='relu'
                   ) (image_input)

        x = MaxPool2D(strides=2, pool_size = 2) (x)

        x = Conv2D(filters=50,
                     kernel_size=(5, 5),
                     strides=1,
                     padding='valid',
                     kernel_initializer=initialiser_normal,
                     bias_initializer=initialiser_const,
                     activation='relu'
                   ) (x)

        x = MaxPool2D(strides=2, pool_size = 2) (x)

        x = Flatten() (x)
        # relu
        x = Dense(500,
                  activation='relu',
                  kernel_initializer=initialiser_xavier,
                  bias_initializer=initialiser_const,
                  ) (x)

        x = Concatenate()([head_pose_input, x])

        output = Dense(num_classes, activation='softmax')(x)

        model = Model(inputs = [image_input, head_pose_input], outputs = output)

        #model.compile(
        #    optimizer = tf.keras.optimizers.SGD(),
        #    loss=angle_loss_fn,
        #    metrics=[angle_loss_fn],
        #)

        model.compile(loss='sparse_categorical_crossentropy', optimizer=keras.optimizers.Adam(), metrics=['accuracy'])

        class_weights = class_weight.compute_class_weight(class_weight="balanced",
                                                          classes=np.unique(y_train_labels), y=y_train_labels)
        class_weight_dict = dict(enumerate(class_weights))

        history = model.fit([x_img_train, x_ha_train], y_train_labels, batch_size=128, epochs=50, shuffle=True, validation_split=0.1, verbose=0)

        model.save(os.path.join('trained_models', 'lenet_trained' + "_" + str(embedding) + "_" + str(clustering) + "_" + str(experiment) + '.h5'))

    else:
        model = keras.models.load_model(os.path.join('trained_models', 'lenet_trained' + "_" + str(embedding) + "_" + str(clustering) + "_" + str(experiment) + '.h5'))
        model.compile(loss='sparse_categorical_crossentropy', optimizer=keras.optimizers.Adam(), metrics=['accuracy'])

    score = model.evaluate([x_img_test, x_ha_test], y_test_labels, verbose=0)
    pred_labels = model.predict([x_img_test, x_ha_test], verbose=0)

    predicted_class_labels = np.argmax(pred_labels, axis=1)
    clusters_in_test_set = np.unique(y_test_labels)

    weighted_accuracy_by_pair_nn = []

    for picked_cluster in clusters_in_test_set:
        for other_cluster in clusters_in_test_set:
            if picked_cluster != other_cluster:
                elements_in_picked_cluster = np.where(y_test_labels == picked_cluster)[0]
                elements_in_other_cluster = np.where(y_test_labels == other_cluster)[0]

                predictions_in_picked_cluster = predicted_class_labels[elements_in_picked_cluster]
                predictions_in_other_cluster = predicted_class_labels[elements_in_other_cluster]

                # Classifications in picked cluster
                correct_predictions_picked_cluster = len(
                    np.where(predictions_in_picked_cluster == picked_cluster)[0])
                mispredictions_picked_cluster = len(np.where(predictions_in_picked_cluster == other_cluster)[0])

                # Classifications in other cluster
                correct_predictions_other_cluster = len(np.where(predictions_in_other_cluster == other_cluster)[0])
                mispredictions_other_cluster = len(np.where(predictions_in_other_cluster == picked_cluster)[0])

                # Compute weighted accuracy
                size_picked_cluster = correct_predictions_picked_cluster + mispredictions_picked_cluster
                size_other_cluster = correct_predictions_other_cluster + mispredictions_other_cluster

                n_AA = correct_predictions_picked_cluster  # Number of elements correctly predicted as belonging to cluster A
                n_BB = correct_predictions_other_cluster  # Number of elements correctly predicted as belonging to cluster B
                n_BA = mispredictions_picked_cluster  # Number of elements belonging to cluster A but predicted to belong to cluster B
                n_AB = mispredictions_other_cluster  # Number of elements belonging to cluster B but predicted to belong to cluster A

                if size_picked_cluster > size_other_cluster:
                    if size_other_cluster == 0:
                        continue
                    w = size_picked_cluster / size_other_cluster
                    wacc_pairs = (n_AA + w * n_BB) / (n_AA + w * n_BB + n_BA + w * n_AB)
                else:
                    if size_picked_cluster == 0:
                        continue
                    w = size_other_cluster / size_picked_cluster
                    wacc_pairs = (w * n_AA + n_BB) / (w * n_AA + n_BB + w * n_BA + n_AB)

                weighted_accuracy_by_pair_nn.append(wacc_pairs)

    del model

    min_weighted_accuracy_pair = np.min(weighted_accuracy_by_pair_nn)
    mean_weighted_accuracy_pair = np.mean(weighted_accuracy_by_pair_nn)

    return min_weighted_accuracy_pair, mean_weighted_accuracy_pair


